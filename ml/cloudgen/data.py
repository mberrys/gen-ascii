"""Shard reader for the training exports.

The Objaverse export (`scripts/objaverse-export.ts`) and the procedural export
(`scripts/procedural-export.ts`) write the same folder per run: `meta.json` plus
`shard-NNNNN.points.npy` (float16, `[n, P, 6]`), `.rgb.npy` (`[n, P, 3]`, 255 where a model had
no colour) and `.jsonl` (one row per cloud: uid, title, caption, credit).
`docs/training-export.md` and `docs/procedural-data.md` describe the two sources.

Nothing here downloads anything: the shards are the input, and a shard set whose manifest cannot say
what it was screened by is refused rather than trained on. That is the one rule this module exists to
enforce (J3 in the plan).

A training run can read several folders at once, in groups with a weight each: 20,000 Objaverse
rows beside a million procedural ones would otherwise be 2 per cent of every batch.
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from pathlib import Path

import numpy as np


class UnscreenedShards(RuntimeError):
    """A shard set that cannot say what screening its rows passed."""


@dataclass(frozen=True)
class Manifest:
    index: str
    rows: int
    points: int
    screened: object
    revisions: dict[str, str]
    folder: str = ""
    provenance: dict | None = None

    @classmethod
    def read(cls, folder: Path) -> "Manifest":
        path = folder / "meta.json"
        if not path.exists():
            raise UnscreenedShards(f"{folder} has no meta.json, so nothing says what the rows were screened by")
        meta = json.loads(path.read_text(encoding="utf-8"))
        if "screened" not in meta:
            raise UnscreenedShards("meta.json does not carry a screening field")
        return cls(
            index=str(meta.get("index", "")),
            rows=int(meta.get("rows", 0)),
            points=int(meta.get("points", 0)),
            screened=meta.get("screened"),
            revisions=dict(meta.get("revisions", {})),
            # absolute, so the clean script can tell which runs read which folder
            folder=str(folder.resolve()),
            provenance=meta.get("provenance"),
        )

    @property
    def screening_note(self) -> str:
        """What to print next to a training run, so the numbers carry their provenance."""
        if isinstance(self.screened, list) and any(
            isinstance(s, str) and s.startswith("procedural:") for s in self.screened
        ):
            return "generated by this repo's generators"
        if isinstance(self.screened, list) and self.screened:
            return f"{len(self.screened)} uids checked by scripts/objaverse-nsfw.py"
        if self.index.endswith("-20000") and self.screened is None:
            return "the shipped index, whose every row the image classifier screened"
        return "unknown"


@dataclass
class Shard:
    folder: Path
    manifest: Manifest
    points: np.ndarray  # [n, P, 6] float16, mmapped
    captions: list[str]
    rows: list[dict]

    @property
    def n(self) -> int:
        return int(self.points.shape[0])

    def clouds(self, idx: np.ndarray) -> np.ndarray:
        """The clouds at `idx`, float32 and copied out of the mmap."""
        return np.asarray(self.points[idx], dtype=np.float32)


def load_shards(folder: str | Path, limit_shards: int | None = None) -> tuple[Manifest, list[Shard]]:
    folder = Path(folder)
    manifest = Manifest.read(folder)
    files = sorted(folder.glob("shard-*.points.npy"))
    if not files:
        raise FileNotFoundError(f"no shard-*.points.npy in {folder}")
    shards: list[Shard] = []
    for file in files[:limit_shards]:
        stem = file.name[: -len(".points.npy")]
        lines = (folder / f"{stem}.jsonl").read_text(encoding="utf-8").splitlines()
        rows = [json.loads(line) for line in lines if line.strip()]
        points = np.load(file, mmap_mode="r")
        if len(rows) != points.shape[0]:
            raise ValueError(f"{file.name} holds {points.shape[0]} clouds and {len(rows)} captions")
        shards.append(
            Shard(
                folder=folder,
                manifest=manifest,
                points=points,
                captions=[str(r.get("caption") or r.get("title") or "") for r in rows],
                rows=rows,
            )
        )
    return manifest, shards


def turn_about_y(pos: np.ndarray, nrm: np.ndarray, angle: float) -> None:
    """Turn xyz and the normals about Y, in place.

    The export keeps each model's own facing, so the same object arrives turned any way about the
    vertical axis. A random turn in training is what makes the app's turntable irrelevant to the
    model: it learns the shape, not which side happened to be exported toward +Z.
    """
    c, s = np.cos(angle), np.sin(angle)
    for xyz in (pos, nrm):
        x = xyz[..., 0].copy()
        z = xyz[..., 2].copy()
        xyz[..., 0] = x * c + z * s
        xyz[..., 2] = z * c - x * s


@dataclass
class Group:
    """One `--data` argument: the folders it named, their shards, and its share of each batch."""

    folders: list[str]
    manifests: list[Manifest]
    shards: list[Shard]
    weight: float | None = None

    @property
    def rows(self) -> int:
        return sum(s.n for s in self.shards)

    def record(self) -> dict:
        """What a run's train.json says about this group, so a checkpoint names every folder it read."""
        return {
            "folders": self.folders,
            "weight": self.weight,
            "rows": self.rows,
            "shards": len(self.shards),
            "manifests": [
                {
                    "folder": m.folder, "index": m.index, "rows": m.rows, "screening": m.screening_note,
                    "revisions": m.revisions, "provenance": m.provenance,
                }
                for m in self.manifests
            ],
        }


def load_groups(groups: list[list[str]], limit_shards: int | None = None) -> list[Group]:
    """Each inner list is one group of folders. Every folder is checked by the rules in `load_shards`."""
    out: list[Group] = []
    points: int | None = None
    for folders in groups:
        manifests: list[Manifest] = []
        shards: list[Shard] = []
        for folder in folders:
            manifest, found = load_shards(folder, limit_shards=limit_shards)
            width = int(found[0].points.shape[1])
            if points is None:
                points = width
            elif width != points:
                raise ValueError(f"{folder} holds clouds of {width} points and an earlier folder {points}")
            manifests.append(manifest)
            shards.extend(found)
        out.append(Group(folders=list(folders), manifests=manifests, shards=shards))
    return out


def parse_mix(text: str | None, groups: int) -> list[float] | None:
    """`--mix 0.75,0.25` to weights that sum to one, or None for one draw over every row."""
    if not text:
        return None
    try:
        weights = [float(w) for w in text.split(",")]
    except ValueError:
        raise ValueError(f"--mix takes numbers separated by commas, not {text!r}") from None
    if len(weights) != groups:
        raise ValueError(f"--mix has {len(weights)} weights for {groups} --data groups")
    if any(not np.isfinite(w) or w <= 0 for w in weights):
        raise ValueError("every --mix weight must be a positive number")
    total = sum(weights)
    return [w / total for w in weights]


def caption_table(captions: list[str]) -> tuple[list[str], np.ndarray]:
    """The distinct captions in first-seen order, and each row's position in them.

    Procedural captions are templated, so a million rows hold a few thousand sentences. The text
    encoder runs over the distinct ones and the training loop indexes through `ids`.
    """
    seen: dict[str, int] = {}
    ids = np.fromiter((seen.setdefault(c, len(seen)) for c in captions), dtype=np.int64, count=len(captions))
    return list(seen), ids


class CloudDataset:
    """Batches of `[B, P, 6]` clouds with their captions, drawn from the shards in order.

    With `groups` and `weights`, each batch slot first picks a group by weight and then a row in it.
    Without them, a batch is one draw over every row, as it was before groups existed, so a run
    with one folder and no `--mix` draws the same batches it always did.
    """

    def __init__(
        self,
        shards: list[Shard],
        seed: int = 0,
        turn: bool = True,
        groups: list[int] | None = None,
        weights: list[float] | None = None,
    ):
        self.shards = shards
        self.seed = seed
        self.turn = turn
        self.rng = np.random.default_rng(seed)
        # an index of every row, so a batch can span shards after the first pass
        self.index = [(s, i) for s, shard in enumerate(shards) for i in range(shard.n)]
        self.weights = weights
        self.spans: list[tuple[int, int]] = []
        if weights is not None:
            if groups is None or len(groups) != len(shards):
                raise ValueError("weights need a group for every shard")
            if list(groups) != sorted(groups):
                raise ValueError("shards must be listed group by group")
            count = max(groups) + 1 if groups else 0
            if len(weights) != count:
                raise ValueError(f"{len(weights)} weights for {count} groups")
            ends = [0] * count
            for g, shard in zip(groups, shards):
                ends[g] += shard.n
            start = 0
            for n in ends:
                if n == 0:
                    raise ValueError("a weighted group holds no rows")
                self.spans.append((start, start + n))
                start += n

    def __len__(self) -> int:
        return len(self.index)

    def _take(self, size: int) -> np.ndarray:
        if self.weights is None:
            return self.rng.choice(len(self.index), size=size, replace=False)
        per = self.rng.multinomial(size, self.weights)
        parts = []
        for (start, end), k in zip(self.spans, per):
            if k:
                n = end - start
                # a group smaller than its share of one batch repeats rows rather than failing
                parts.append(start + self.rng.choice(n, size=int(k), replace=bool(k > n)))
        take = np.concatenate(parts)
        self.rng.shuffle(take)
        return take

    def batch(self, size: int) -> tuple[np.ndarray, np.ndarray, list[str]]:
        take = self._take(size)
        out = np.empty((size, self.shards[0].points.shape[1], 6), dtype=np.float32)
        captions: list[str] = [""] * size
        # gathered a shard at a time: one fancy-index into the mmap per shard instead of one per row,
        # which is most of what the step spent its time on
        grouped: dict[int, list[tuple[int, int]]] = {}
        for j, k in enumerate(take):
            s, i = self.index[int(k)]
            grouped.setdefault(s, []).append((j, i))
        for s, pairs in grouped.items():
            shard = self.shards[s]
            clouds = shard.clouds(np.asarray([i for _, i in pairs]))
            for (j, i), cloud in zip(pairs, clouds):
                if self.turn:
                    turn_about_y(cloud[:, :3], cloud[:, 3:], float(self.rng.uniform(0, 2 * np.pi)))
                out[j] = cloud
                captions[j] = shard.captions[i]
        return out, np.asarray(take, dtype=np.int64), captions

    def captions(self) -> list[str]:
        """Every caption, in the order `batch` indexes them. The text encoder runs once over this."""
        return [self.shards[s].captions[i] for s, i in self.index]
