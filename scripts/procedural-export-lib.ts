// The parts of the procedural export that decide what a run writes and whether its shards can be
// rebuilt later: the arguments, the row plan, the manifest and the record of the code that ran.
// They live apart from the export's main loop so the clean script (scripts/procedural-clean.ts)
// and the tests can use them without running an export.

import { execFileSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import { readFileSync } from 'node:fs'

// Bumped when the meaning of a shard changes, so a resumed run never mixes two formats.
export const FORMAT = 1

// What the loader prints next to a run. A list, because the Objaverse export writes the uids an
// image classifier checked; here the single entry says the rows are this repo's own work.
export const SCREENED = ['procedural: generated by scripts/procedural-export.ts']

// Everything the bundle is built from. A change here, uncommitted, means the commit recorded in
// meta.json does not describe the code that wrote the shards.
export const SOURCE_PATHS = ['src', 'scripts', 'package.json', 'package-lock.json']

export type Args = {
  out: string
  count: number
  shard: number
  points: number
  seed: number
  limitItems: number
  rgb: boolean
  allowDirty: boolean
}

export const parseArgs = (argv: string[]): Args => {
  const a: Args = { out: '', count: 1000, shard: 1000, points: 4096, seed: 0, limitItems: 0, rgb: true, allowDirty: false }
  for (let i = 0; i < argv.length; i++) {
    const k = argv[i]
    const value = () => {
      const v = argv[++i]
      if (v === undefined || v.startsWith('--')) throw new Error(`${k} needs a value`)
      return v
    }
    // a whole number, at least `min`: a typo stops the run rather than turning into "no limit"
    const count = (min: number) => {
      const v = value()
      const n = Number(v)
      if (!/^\d+$/.test(v) || !Number.isSafeInteger(n) || n < min) throw new Error(`${k} must be a whole number of at least ${min}, not ${v}`)
      return n
    }
    if (k === '--out') a.out = value()
    else if (k === '--count') a.count = count(1)
    else if (k === '--shard') a.shard = count(1)
    else if (k === '--points') a.points = count(1)
    else if (k === '--seed') a.seed = count(0)
    else if (k === '--limit-items') a.limitItems = count(1)
    else if (k === '--no-rgb') a.rgb = false
    else if (k === '--allow-dirty') a.allowDirty = true
    else throw new Error(`unknown option ${k}`)
  }
  if (!a.out) throw new Error('--out is required: the folder the shards are written into')
  return a
}

export type Planned<T> = { item: T; seed: number }

// The item by item sweep of the seeds, cut at `count`. Seed 0 is every form's canonical shape, so
// a small run starts with the nine the app shows before anything is rerolled. A run's first `n`
// rows are the same whatever its `count`, which is what lets one shard be rebuilt on its own.
export const plan = <T>(items: T[], count: number, seed0: number): Planned<T>[] => {
  if (!items.length) throw new Error('no items to export')
  const rows: Planned<T>[] = []
  for (let seed = seed0; rows.length < count; seed++) {
    for (const item of items) if (rows.length < count) rows.push({ item, seed })
  }
  return rows
}

export const uidOf = (row: Planned<{ id: string }>) => `${row.item.id}-s${row.seed}`

export const shardName = (k: number) => `shard-${String(k).padStart(5, '0')}`

// The code that wrote a run. `dirty` lists the source files that differed from `commit`, so a run
// made from uncommitted code says so and the clean script refuses to delete what it cannot rebuild.
export type Provenance = {
  commit: string
  dirty: string[]
  bundle: string // sha256 of the script file that ran, which esbuild writes byte for byte the same
  node: string
}

// `git status --porcelain` lines to paths. A rename reads "R  old -> new"; the new path is the one
// the bundle would read.
export const dirtyFrom = (porcelain: string): string[] =>
  porcelain
    .split('\n')
    .map((line) => line.trimEnd())
    .filter((line) => line.length > 3)
    .map((line) => {
      const path = line.slice(3)
      const arrow = path.indexOf(' -> ')
      return arrow >= 0 ? path.slice(arrow + 4) : path
    })

const git = (cwd: string, args: string[]) => execFileSync('git', args, { cwd, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] })

export const sha256File = (path: string) => createHash('sha256').update(readFileSync(path)).digest('hex')

export const provenanceOf = (cwd: string, script: string): Provenance => {
  let commit: string
  let dirty: string[]
  try {
    commit = git(cwd, ['rev-parse', 'HEAD']).trim()
    // tracked changes only: an untracked file can only reach the bundle through a tracked file
    // that imports it, and that file would show here
    dirty = dirtyFrom(git(cwd, ['status', '--porcelain', '--untracked-files=no', '--', ...SOURCE_PATHS]))
  } catch {
    throw new Error('the export records the git commit it ran at, and git could not say what it is; run it inside the repository')
  }
  return { commit, dirty, bundle: sha256File(script), node: process.version }
}

// A run from uncommitted code writes shards nobody can rebuild, so it needs to be asked for.
export const checkClean = (p: Provenance, allowDirty: boolean) => {
  if (p.dirty.length && !allowDirty) {
    const shown = p.dirty.slice(0, 8).join(', ') + (p.dirty.length > 8 ? `, and ${p.dirty.length - 8} more` : '')
    throw new Error(
      `uncommitted changes in ${shown}: shards written now could not be rebuilt from ${p.commit.slice(0, 12)}. ` +
        'Commit them first, or pass --allow-dirty for a run that will never be deleted and rebuilt',
    )
  }
}

export type Meta = {
  format: number
  index: 'procedural'
  rows: number
  points: number
  shard: number
  rgb: boolean
  screened: string[]
  revisions: Record<string, string>
  uids: string
  items: string[]
  seed: number
  provenance: Provenance
  channels: { points: string[]; rgb?: string[] }
  space: string
  sampler: string
}

export const metaFor = (args: Args, rows: Planned<{ id: string }>[], items: { id: string }[], provenance: Provenance): Meta => ({
  format: FORMAT,
  index: 'procedural',
  rows: rows.length,
  points: args.points,
  shard: args.shard,
  rgb: args.rgb,
  screened: SCREENED,
  revisions: {},
  // the rows themselves, so a run with another --count, --seed or set of items is refused
  // rather than resuming into a shard that would hold a different set
  uids: createHash('sha256').update(rows.map(uidOf).join('\n')).digest('hex'),
  items: items.map((i) => i.id),
  seed: args.seed,
  provenance,
  channels: args.rgb ? { points: ['x', 'y', 'z', 'nx', 'ny', 'nz'], rgb: ['r', 'g', 'b'] } : { points: ['x', 'y', 'z', 'nx', 'ny', 'nz'] },
  space: 'unit sphere, centred on the bounding box, farthest point at radius 1',
  sampler: 'src/core/sample.ts sampleSoup: blue noise, Morton ordered, seeded per cloud',
})

// Why a run cannot resume into a folder that already holds one, or null when it can. The code has
// to match as well as the rows: a resumed run from another commit or build would mix two sets of
// shards under one manifest.
export const resumeConflict = (was: Partial<Meta>, now: Meta): string | null => {
  for (const key of ['format', 'index', 'points', 'shard', 'rows', 'uids', 'seed', 'rgb'] as const) {
    if (JSON.stringify(was[key]) !== JSON.stringify(now[key])) {
      if (key === 'rows' || key === 'uids') return 'set of rows (another --count, --seed or set of items)'
      if (key === 'rgb') return 'colour setting (--no-rgb on one run and not the other)'
      return key
    }
  }
  if (!was.provenance) return 'export from before runs recorded their commit'
  if (was.provenance.commit !== now.provenance.commit) return `commit (${was.provenance.commit.slice(0, 12)})`
  if (was.provenance.bundle !== now.provenance.bundle) return 'build of the export script'
  if (JSON.stringify(was.provenance.dirty) !== JSON.stringify(now.provenance.dirty)) return 'set of uncommitted changes'
  return null
}

// The arguments that rebuild a run's first shard, and the full run, from its manifest.
export const rebuildArgs = (meta: Meta, out: string, firstShardOnly: boolean): string[] => [
  '--out', out,
  '--count', String(firstShardOnly ? Math.min(meta.shard, meta.rows) : meta.rows),
  '--seed', String(meta.seed),
  '--shard', String(meta.shard),
  '--points', String(meta.points),
  '--limit-items', String(meta.items.length),
  ...(meta.rgb ? [] : ['--no-rgb']),
]
